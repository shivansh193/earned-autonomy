#!/bin/sh
# RELEASE (routing): find the MR this main-branch commit came from, read the
# autonomy:: label the Autonomy Router set, and generate the prod promotion
# pipeline accordingly:
#   hands-off            -> promote automatically
#   supervised/assisted  -> promote only after a manual approval (a person clicks)
#   blocked / no label   -> manual (conservative default)
set -eu
apk add -q --no-cache curl jq >/dev/null 2>&1 || true
mkdir -p reports
# One read of the commit's MRs, retried: a failed read must not silently become "no label".
MRS=""
for attempt in 1 2 3 4 5; do
  MRS=$(curl -sf "${CI_API_V4_URL}/projects/${CI_PROJECT_ID}/repository/commits/${CI_COMMIT_SHA}/merge_requests" || true)
  echo "$MRS" | jq -e 'type == "array"' >/dev/null 2>&1 && break
  echo "reading the commit's merge requests failed (attempt $attempt); retrying"
  MRS=""; sleep $((attempt * 3))
done
LEVEL=$(echo "${MRS:-[]}" | jq -r '[.[] | select(.state == "merged") | .labels[] | select(startswith("autonomy::"))] | first // "none"' |
  sed 's/^autonomy:://')
MR=$(echo "${MRS:-[]}" | jq -r '[.[] | select(.state == "merged") | .iid] | first // "none"')
[ -z "$MRS" ] && echo "could not read the merge request after 5 attempts: promoting with a manual approval"

# A manual promotion is a blocking approval gate (allow_failure: false), so the
# pipeline waits for the person and monitor-prod runs right after the click.
case "$LEVEL" in
  hands-off) WHEN=on_success; ALLOW_FAILURE=false ;;
  *)         WHEN=manual;     ALLOW_FAILURE=false ;;
esac
echo "MR !${MR}: autonomy=${LEVEL} -> prod promotion when=${WHEN}"
printf 'EA_ROUTED_LEVEL=%s\nEA_ROUTED_MR=%s\n' "$LEVEL" "$MR" > reports/route.env

cat > reports/promote.yml <<EOF
# Generated by ci/route.sh for MR !${MR} (autonomy::${LEVEL}).
include:
  - local: ci/promote-base.yml
promote-prod:
  extends: .promote-prod
  when: ${WHEN}
  allow_failure: ${ALLOW_FAILURE}
  variables:
    EA_LEVEL: "${LEVEL}"
    EA_IMAGE: "${EA_IMAGE}"
monitor-prod:
  extends: .monitor-prod
  variables:
    EA_MR: "${MR}"
    EA_LEVEL: "${LEVEL}"
EOF
cat reports/promote.yml

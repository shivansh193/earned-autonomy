#!/bin/sh
# RELEASE (routing): find the MR this main-branch commit came from, read the
# autonomy:: label the Autonomy Router set, and generate the prod promotion
# pipeline accordingly:
#   hands-off            -> promote automatically
#   supervised/assisted  -> promote only after a manual approval (a person clicks)
#   blocked / no label   -> manual (conservative default)
set -eu
apk add -q --no-cache curl jq >/dev/null 2>&1 || true
mkdir -p reports
LEVEL=$(curl -sf "${CI_API_V4_URL}/projects/${CI_PROJECT_ID}/repository/commits/${CI_COMMIT_SHA}/merge_requests" |
  jq -r '[.[] | select(.state == "merged") | .labels[] | select(startswith("autonomy::"))] | first // "none"' |
  sed 's/^autonomy:://')
MR=$(curl -sf "${CI_API_V4_URL}/projects/${CI_PROJECT_ID}/repository/commits/${CI_COMMIT_SHA}/merge_requests" |
  jq -r '[.[] | select(.state == "merged") | .iid] | first // "none"')

case "$LEVEL" in
  hands-off) WHEN=on_success ;;
  *)         WHEN=manual ;;
esac
echo "MR !${MR}: autonomy=${LEVEL} -> prod promotion when=${WHEN}"
printf 'EA_ROUTED_LEVEL=%s\nEA_ROUTED_MR=%s\n' "$LEVEL" "$MR" > reports/route.env

cat > reports/promote.yml <<EOF
# Generated by ci/route.sh for MR !${MR} (autonomy::${LEVEL}).
include:
  - local: ci/promote-base.yml
promote-prod:
  extends: .promote-prod
  when: ${WHEN}
  variables:
    EA_LEVEL: "${LEVEL}"
    EA_IMAGE: "${EA_IMAGE}"
EOF
cat reports/promote.yml
